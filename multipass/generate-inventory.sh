#!/usr/bin/env bash
# multipass/generate-inventory.sh
# Dynamically queries Multipass VM IP addresses and writes inventories/local/hosts.yml
# supporting the 3-Layer Architecture (Layer 1 Infrastructure, Layer 2 Mgmt K8s, Layer 3 App K8s).
#
# Usage:
#   ./multipass/generate-inventory.sh [--profile compact|minimal|ha] [--running-only]

set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
PROJECT_ROOT="$(cd "${SCRIPT_DIR}/.." && pwd)"
PROFILE="${MULTIPASS_PROFILE:-compact}"
OUTPUT_FILE="${PROJECT_ROOT}/inventories/local/hosts.yml"
RUNNING_ONLY=false

while [[ $# -gt 0 ]]; do
  case "$1" in
    -p|--profile)
      PROFILE="$2"
      shift 2
      ;;
    -o|--output)
      OUTPUT_FILE="$2"
      shift 2
      ;;
    --running-only)
      RUNNING_ONLY=true
      shift
      ;;
    *)
      echo "[ERROR] Unknown argument: $1" >&2
      exit 1
      ;;
  esac
done

PROFILE_FILE="${SCRIPT_DIR}/profiles/${PROFILE}.conf"
if [[ ! -f "${PROFILE_FILE}" ]]; then
  echo "[ERROR] Profile file not found: ${PROFILE_FILE}" >&2
  exit 1
fi

echo "[INFO] Generating 3-Layer Ansible inventory at ${OUTPUT_FILE} (profile: ${PROFILE}, running_only: ${RUNNING_ONLY})..."

EXISTING_CSV="$(multipass list --format csv | tail -n +2 || true)"

get_vm_ip() {
  local vm="$1"
  local row
  row="$(echo "${EXISTING_CSV}" | grep "^${vm}," || true)"
  if [[ -n "${row}" ]]; then
    echo "${row}" | cut -d',' -f3 | awk '{print $1}'
  else
    echo ""
  fi
}

is_vm_running() {
  local vm="$1"
  local row
  row="$(echo "${EXISTING_CSV}" | grep "^${vm}," || true)"
  if [[ -n "${row}" ]]; then
    local state
    state="$(echo "${row}" | cut -d',' -f2)"
    [[ "${state}" == "Running" ]]
    return $?
  fi
  return 1
}

render_group_hosts() {
  local target_group="$1"
  local idx=0
  local matched=0
  while IFS='|' read -r vm_name vm_cpus vm_mem vm_disk vm_groups; do
    [[ -z "${vm_name}" || "${vm_name}" =~ ^# ]] && continue
    if [[ ",${vm_groups}," == *",${target_group},"* ]]; then
      if [[ "${RUNNING_ONLY}" == "true" ]] && ! is_vm_running "${vm_name}"; then
        idx=$(( idx + 1 ))
        continue
      fi
      local ip
      ip="$(get_vm_ip "${vm_name}")"
      if [[ -z "${ip}" ]]; then
        ip="192.168.252.$(( 10 + idx ))"
      fi
      echo "            ${vm_name}:"
      echo "              ansible_host: \"${ip}\""
      if [[ "${target_group}" == "k8s_control_plane" || "${target_group}" == "k8s_mgmt_control_plane" ]]; then
        echo "              k8s_node_role: control-plane"
        if [[ ${matched} -eq 0 ]]; then
          echo "              k8s_init_node: true"
        else
          echo "              k8s_init_node: false"
        fi
      elif [[ "${target_group}" == "k8s_workers" ]]; then
        echo "              k8s_node_role: worker"
      elif [[ "${target_group}" == "postgresql_ha" ]]; then
        if [[ "${vm_name}" == "pg-db1" || ${matched} -eq 0 ]]; then
          echo "              pg_ha_role: leader"
          echo "              patroni_priority: 110"
        elif [[ "${vm_name}" == "pg-db2" || ${matched} -eq 1 ]]; then
          echo "              pg_ha_role: sync_standby"
          echo "              patroni_priority: 100"
        else
          echo "              pg_ha_role: async_replica"
          echo "              patroni_priority: 90"
        fi
      fi
      idx=$(( idx + 1 ))
      matched=$(( matched + 1 ))
    fi
  done < "${PROFILE_FILE}"
  if [[ ${matched} -eq 0 ]]; then
    echo "            {}"
  fi
}

cat > "${OUTPUT_FILE}" <<EOF
---
# Auto-generated by multipass/generate-inventory.sh (3-Layer Architecture)
# Profile: ${PROFILE}
# Generated at: $(date -u +"%Y-%m-%dT%H:%M:%SZ")

all:
  children:
    # ==========================================================================
    # Layer 1: DevOps, Databases, Object Storage, Monitoring & Backup (Outside K8s)
    # ==========================================================================
    devops_core:
      children:
        gitlab:
          hosts:
$(render_group_hosts "gitlab")
        jenkins:
          hosts:
$(render_group_hosts "jenkins")
        jenkins_agents:
          hosts:
$(render_group_hosts "jenkins_agents")
        nexus:
          hosts:
$(render_group_hosts "nexus")
        minio:
          hosts:
$(render_group_hosts "minio")
        postgresql_ha:
          hosts:
$(render_group_hosts "postgresql_ha")
        redis:
          hosts:
$(render_group_hosts "redis")
        monitoring:
          hosts:
$(render_group_hosts "monitoring")
        backup_services:
          hosts:
$(render_group_hosts "backup_services")
        rancher:
          hosts:
$(render_group_hosts "rancher")

    # ==========================================================================
    # Layer 2: Dedicated Kubernetes Management Cluster (Rancher + Argo CD)
    # ==========================================================================
    k8s_mgmt_cluster:
      children:
        k8s_mgmt_control_plane:
          hosts:
$(render_group_hosts "k8s_mgmt_control_plane")

    # ==========================================================================
    # Layer 3: Application Kubernetes Cluster (Business Workloads Only)
    # ==========================================================================
    k8s_app_cluster:
      children:
        k8s_control_plane:
          hosts:
$(render_group_hosts "k8s_control_plane")
        k8s_workers:
          hosts:
$(render_group_hosts "k8s_workers")

    # Backward-compatible group alias for Application Kubernetes Cluster
    k8s_cluster:
      children:
        k8s_control_plane:
        k8s_workers:
EOF

echo "[OK] Ansible inventory successfully updated: ${OUTPUT_FILE}"
